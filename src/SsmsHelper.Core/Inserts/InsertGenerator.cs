using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using SsmsHelper.Core.Metadata;
using SsmsHelper.Core.Parsing;

namespace SsmsHelper.Core.Inserts;

public enum InsertLayout
{
    /// <summary>One column and one value per line, each value commented with column name, type, NULL and default.</summary>
    Expanded,

    /// <summary>"INSERT INTO t (a, b)" then "VALUES (0, N'');" on the next line, without comments.</summary>
    Compact,
}

/// <param name="NullForNullable">Use NULL instead of a typed placeholder for nullable columns.</param>
public sealed record InsertOptions(bool NullForNullable = false)
{
    public static InsertOptions Default { get; } = new();
}

/// <summary>Text inserted at <see cref="InsertContext.ReplaceStart"/>, with the caret offset inside it.</summary>
public sealed record InsertExpansion(string Text, int CaretOffset);

/// <summary>A column left out of the generated column list, and why.</summary>
public sealed record SkippedColumn(string Name, string Reason);

/// <summary>
/// Builds the column list and one VALUES row of typed placeholders for an INSERT statement.
/// There is no INSERT ... SELECT form: users edit VALUES into a SELECT when they need one.
/// </summary>
public static class InsertGenerator
{
    private const string Tab = "    ";

    /// <summary>Columns a plain INSERT can set, in sys.columns order.</summary>
    public static IReadOnlyList<ColumnInfo> InsertableColumns(TableInfo table) =>
        table.Columns.Where(c => SkipReason(c) is null).ToList();

    public static IReadOnlyList<SkippedColumn> SkippedColumns(TableInfo table) =>
        table.Columns
            .Select(c => (Column: c, Reason: SkipReason(c)))
            .Where(x => x.Reason is not null)
            .Select(x => new SkippedColumn(x.Column.Name, x.Reason!))
            .ToList();

    public static InsertExpansion Generate(
        InsertContext context, TableInfo table, string newLine, InsertLayout layout = InsertLayout.Expanded, InsertOptions? options = null)
    {
        options ??= InsertOptions.Default;
        var indent = context.Indent;
        var text = new StringBuilder();

        // Rows of (column name, column if known); a user-typed list is kept as typed, even for identity columns.
        IReadOnlyList<(string Name, ColumnInfo? Column)> rows;
        if (context.Columns is not null)
        {
            rows = context.Columns
                .Select(name => (name, (ColumnInfo?)table.Columns.FirstOrDefault(c => string.Equals(c.Name, name, StringComparison.OrdinalIgnoreCase))))
                .ToList();
        }
        else
        {
            rows = InsertableColumns(table).Select(c => (c.Name, (ColumnInfo?)c)).ToList();
            if (rows.Count == 0)
            {
                // Every column is generated by the server.
                const string defaultValues = " DEFAULT VALUES;";
                return new InsertExpansion(defaultValues, defaultValues.Length);
            }

            if (layout == InsertLayout.Compact)
            {
                text.Append(" (").Append(string.Join(", ", rows.Select(r => SqlIdentifier.Quote(r.Name)))).Append(')');
            }
            else
            {
                text.Append(newLine).Append(indent).Append('(');
                for (var i = 0; i < rows.Count; i++)
                {
                    text.Append(newLine).Append(indent).Append(Tab).Append(SqlIdentifier.Quote(rows[i].Name));
                    if (i < rows.Count - 1)
                    {
                        text.Append(',');
                    }
                }

                text.Append(newLine).Append(indent).Append(')');
            }
        }

        var values = rows.Select(r => r.Column is null ? "NULL" : Placeholder(r.Column, options)).ToList();
        if (layout == InsertLayout.Compact)
        {
            text.Append(newLine).Append(indent).Append("VALUES (");
            var first = text.Length;
            text.Append(string.Join(", ", values)).Append(");");
            return new InsertExpansion(text.ToString(), first);
        }

        text.Append(newLine).Append(indent).Append("VALUES");
        text.Append(newLine).Append(indent).Append('(');

        var width = values.Max(v => v.Length) + 1; // room for the comma
        var caret = -1;
        for (var i = 0; i < rows.Count; i++)
        {
            text.Append(newLine).Append(indent).Append(Tab);
            if (caret < 0)
            {
                caret = text.Length;
            }

            var value = values[i] + (i < rows.Count - 1 ? "," : string.Empty);
            text.Append(value.PadRight(width)).Append(" -- ").Append(Describe(rows[i].Name, rows[i].Column));
        }

        text.Append(newLine).Append(indent).Append(");");

        return new InsertExpansion(text.ToString(), caret);
    }

    /// <summary>A literal of the column's type that SQL Server accepts as-is.</summary>
    public static string Placeholder(ColumnInfo column, InsertOptions? options = null)
    {
        if (column.IsNullable && (options ?? InsertOptions.Default).NullForNullable)
        {
            return "NULL";
        }

        switch (column.BaseTypeName.ToLowerInvariant())
        {
            case "int":
            case "bigint":
            case "smallint":
            case "tinyint":
            case "bit":
                return "0";
            case "decimal":
            case "numeric":
                return column.Scale == 0 ? "0" : "0." + new string('0', column.Scale);
            case "money":
            case "smallmoney":
                return "0.00";
            case "float":
            case "real":
                return "0.0";
            case "nvarchar":
            case "nchar":
            case "ntext":
            case "xml":
                return "N''";
            case "varchar":
            case "char":
            case "text":
                return "''";
            case "json":
                return "N'{}'";
            case "date":
            case "datetime":
            case "datetime2":
            case "smalldatetime":
                return "GETDATE()";
            case "datetimeoffset":
                return "SYSDATETIMEOFFSET()";
            case "time":
                return "CAST(GETDATE() AS time)";
            case "uniqueidentifier":
                return "NEWID()";
            case "binary":
            case "varbinary":
            case "image":
                return "0x";
            default:
                // sql_variant, hierarchyid, geography, geometry, vector and unknown types.
                return "NULL";
        }
    }

    /// <summary>Declared type as it would appear in CREATE TABLE, e.g. "nvarchar(100)" or "decimal(10, 2)".</summary>
    public static string FormatType(ColumnInfo column)
    {
        if (!string.Equals(column.TypeName, column.BaseTypeName, StringComparison.OrdinalIgnoreCase))
        {
            return column.TypeName; // alias type such as sysname
        }

        var type = column.TypeName.ToLowerInvariant();
        switch (type)
        {
            case "varchar":
            case "char":
            case "varbinary":
            case "binary":
                return $"{type}({Length(column.MaxLength)})";
            case "nvarchar":
            case "nchar":
                return $"{type}({(column.MaxLength < 0 ? "max" : (column.MaxLength / 2).ToString(CultureInfo.InvariantCulture))})";
            case "decimal":
            case "numeric":
                return $"{type}({column.Precision}, {column.Scale})";
            case "datetime2":
            case "datetimeoffset":
            case "time":
                return column.Scale == 7 ? type : $"{type}({column.Scale})";
            default:
                return type;
        }

        static string Length(short maxLength) => maxLength < 0 ? "max" : maxLength.ToString(CultureInfo.InvariantCulture);
    }

    private static string Describe(string name, ColumnInfo? column)
    {
        if (column is null)
        {
            return $"{name}: not a column of this table";
        }

        var text = new StringBuilder(column.Name).Append(' ').Append(FormatType(column));
        if (column.IsNullable)
        {
            text.Append(" NULL");
        }

        if (column.DefaultDefinition is not null)
        {
            text.Append(" DEFAULT ").Append(column.DefaultDefinition);
        }

        var skip = SkipReason(column);
        if (skip is not null)
        {
            text.Append(" (").Append(skip).Append(')');
        }

        return text.ToString();
    }

    private static string? SkipReason(ColumnInfo column) =>
        column.IsIdentity ? "identity"
        : column.IsComputed ? "computed"
        : column.IsRowVersion ? "rowversion"
        : column.GeneratedAlways != GeneratedAlwaysType.None ? "generated always"
        : null;
}
